// Mechanical files: changes nobody writes by hand, collapsed into one last step and checked for consistency instead.
import path from 'node:path';
import { type ChangedFile, fileAt, gitWith } from './change';

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
  'Cargo.lock',
  'Gemfile.lock',
  'poetry.lock',
  'Pipfile.lock',
  'uv.lock',
  'composer.lock',
  'go.sum',
  'pubspec.lock',
  'Podfile.lock',
  'packages.lock.json',
  'gradle.lockfile',
  'flake.lock',
  'mix.lock',
  'Package.resolved',
]);
const VENDORED = new Set(['vendor', 'vendors', 'third_party', 'third-party', 'node_modules', 'bower_components', 'Pods']);
const GENERATED_HEADER =
  /@generated\b|\bdo not (edit|modify)\b|<auto-generated|\bauto-?generated\b|\bcode generated by\b|\bgenerated code\b/i;

/** Each mechanical file among `files` with the reason it is mechanical; attributes and headers are read at the head. */
export function mechanicalFiles(cwd: string, base: string, head: string, files: ChangedFile[]): Map<string, string> {
  const reasons = new Map<string, string>();
  const candidates = files.map(file => file.path).filter(file => path.posix.basename(file) !== '.gitignore');
  const attributes = generatedByAttributes(cwd, head, candidates);
  for (const file of candidates) {
    const reason = LOCKFILES.has(path.posix.basename(file))
      ? 'lockfile'
      : file.split('/').includes('__snapshots__') || /\.snap$|\.verified\.[^/]+$/.test(file)
        ? 'snapshot'
        : file.split('/').slice(0, -1).some(folder => VENDORED.has(folder))
          ? 'vendored'
          : attributes.get(file);
    if (reason) reasons.set(file, reason);
    else if (GENERATED_HEADER.test(firstLines(fileAt(cwd, head, file) ?? fileAt(cwd, base, file) ?? '')))
      reasons.set(file, 'generated, per its header');
  }
  return reasons;
}

const firstLines = (text: string) => text.slice(0, 2000).split('\n').slice(0, 5).join('\n');

/** Files .gitattributes at the head marks `linguist-generated` or `linguist-vendored`, as GitHub folds them. */
function generatedByAttributes(cwd: string, head: string, files: string[]): Map<string, string> {
  const found = new Map<string, string>();
  if (files.length === 0) return found;
  const fields = gitWith(
    cwd,
    files.join('\0'),
    'check-attr',
    '-z',
    '--stdin',
    '--source',
    head,
    'linguist-generated',
    'linguist-vendored',
  ).split('\0');
  for (let at = 0; at + 2 < fields.length; at += 3) {
    const [file = '', attribute, value] = fields.slice(at, at + 3);
    if (value !== 'set' && value !== 'true') continue;
    if (attribute === 'linguist-generated') found.set(file, 'generated, per .gitattributes');
    else if (!found.has(file)) found.set(file, 'vendored, per .gitattributes');
  }
  return found;
}

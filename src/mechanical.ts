// Mechanical files: changes nobody writes by hand, collapsed into one last step and checked for consistency instead.
import path from 'node:path';
import { type ChangedFile, fileAt, gitWith } from './change';

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
  'Cargo.lock',
  'Gemfile.lock',
  'poetry.lock',
  'Pipfile.lock',
  'uv.lock',
  'composer.lock',
  'go.sum',
  'pubspec.lock',
  'Podfile.lock',
  'packages.lock.json',
  'gradle.lockfile',
  'flake.lock',
  'mix.lock',
  'Package.resolved',
]);
const VENDORED = new Set(['vendor', 'vendors', 'third_party', 'third-party', 'node_modules', 'bower_components', 'Pods']);
const GENERATED_HEADER =
  /@generated\b|\bdo not (edit|modify)\b|<auto-generated|\bauto-?generated\b|\bcode generated by\b|\bgenerated code\b/i;

/** Each mechanical file among `files` with the reason it is mechanical; attributes and headers are read at the head. */
export function mechanicalFiles(cwd: string, base: string, head: string, files: ChangedFile[]): Map<string, string> {
  const reasons = new Map<string, string>();
  const candidates = files.map(file => file.path).filter(file => path.posix.basename(file) !== '.gitignore');
  const attributes = generatedByAttributes(cwd, head, candidates);
  for (const file of candidates) {
    const reason = LOCKFILES.has(path.posix.basename(file))
      ? 'lockfile'
      : file.split('/').includes('__snapshots__') || /\.snap$|\.verified\.[^/]+$/.test(file)
        ? 'snapshot'
        : file.split('/').slice(0, -1).some(folder => VENDORED.has(folder))
          ? 'vendored'
          : attributes.get(file);
    if (reason) reasons.set(file, reason);
    // Simplification: one git process per file; batch through `git cat-file --batch` if large changes get slow.
    else if (GENERATED_HEADER.test(firstLines(fileAt(cwd, head, file) ?? fileAt(cwd, base, file) ?? '')))
      reasons.set(file, 'generated, per its header');
  }
  return reasons;
}

const NPM_LOCKFILES = ['package-lock.json', 'npm-shrinkwrap.json'];
const NPM_DEPENDENCIES = ['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies'] as const;

/** What makes the mechanical files inconsistent at the head: lockfiles off their manifest, or left mid-merge. */
export function consistencyProblems(
  cwd: string,
  head: string,
  files: ChangedFile[],
  mechanical: Map<string, string>,
): string[] {
  const problems: string[] = [];
  for (const file of mechanical.keys()) {
    if (/^(<{7}|>{7})( |$)/m.test(fileAt(cwd, head, file) ?? '')) problems.push(`${file} has merge conflict markers`);
  }
  // Simplification: npm only; yarn, pnpm and other lockfiles need their own formats parsed.
  const npmFolders = new Set(
    files
      .map(file => file.path)
      .filter(file => ['package.json', ...NPM_LOCKFILES].includes(path.posix.basename(file)))
      .map(file => path.posix.dirname(file)),
  );
  for (const folder of npmFolders) {
    const at = (name: string) => (folder === '.' ? name : `${folder}/${name}`);
    const manifest = parsed(fileAt(cwd, head, at('package.json')));
    const lockName = NPM_LOCKFILES.map(at).find(name => fileAt(cwd, head, name) !== null);
    // Lockfile version 1 has no root package to compare against.
    const root = lockName ? (parsed(fileAt(cwd, head, lockName))?.['packages'] as Json | undefined)?.[''] : undefined;
    if (!manifest || !lockName || !root || typeof root !== 'object') continue;
    for (const field of NPM_DEPENDENCIES) {
      const wanted = (manifest[field] ?? {}) as Json;
      const locked = ((root as Json)[field] ?? {}) as Json;
      for (const name of new Set([...Object.keys(wanted), ...Object.keys(locked)])) {
        if (wanted[name] === locked[name]) continue;
        const said = (where: Json, file: string) =>
          typeof where[name] === 'string' ? `${where[name]} in ${file}` : `missing from ${file}`;
        problems.push(
          `${lockName} does not match ${at('package.json')}: ${field} ${name} is ${said(wanted, at('package.json'))} but ${said(locked, lockName)}`,
        );
      }
    }
  }
  return problems;
}

type Json = Record<string, unknown>;
function parsed(text: string | null): Json | null {
  try {
    const value: unknown = JSON.parse(text ?? '');
    return value && typeof value === 'object' ? (value as Json) : null;
  } catch {
    return null;
  }
}

const firstLines =(text: string) => text.slice(0, 2000).split('\n').slice(0, 5).join('\n');

/** Files .gitattributes at the head marks `linguist-generated` or `linguist-vendored`, as GitHub folds them. */
function generatedByAttributes(cwd: string, head: string, files: string[]): Map<string, string> {
  const found = new Map<string, string>();
  if (files.length === 0) return found;
  const fields = gitWith(
    cwd,
    files.join('\0'),
    'check-attr',
    '-z',
    '--stdin',
    '--source',
    head,
    'linguist-generated',
    'linguist-vendored',
  ).split('\0');
  for (let at = 0; at + 2 < fields.length; at += 3) {
    const [file = '', attribute, value] = fields.slice(at, at + 3);
    if (value !== 'set' && value !== 'true') continue;
    if (attribute === 'linguist-generated') found.set(file, 'generated, per .gitattributes');
    else if (!found.has(file)) found.set(file, 'vendored, per .gitattributes');
  }
  return found;
}
